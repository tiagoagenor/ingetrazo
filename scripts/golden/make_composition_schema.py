"""The sheet item dataclasses of ``core/composition.py`` as a Rust table
(docs/rust-rewrite-plan.md, M2.9).

Opening a document rebuilds each sheet with ``Composicion.from_dict`` and
saving writes ``to_dict``: a record is rewritten with EVERY field its
dataclass declares, in declaration order, the missing ones at their
defaults (a document saved by an older version gains keys; one from a newer
version loses the keys this version does not know). The Rust model keeps
sheets as JSON values and does the same rewrite from this table
(rust/crates/ingetrazo-model/src/composition.rs).

    PYTHONPATH=. .venv/Scripts/python.exe scripts/golden/make_composition_schema.py

Deleted with the Python app at M10.
"""
from __future__ import annotations

import dataclasses
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from core import composition as comp  # noqa: E402

OUT = (ROOT / "rust" / "crates" / "ingetrazo-model" / "src"
       / "composition_schema.rs")

#: Item class -> the key of its list in a sheet's record is in composition.rs.
KINDS = ("MarcoVista", "TextoItem", "ImagenItem", "Cajetin", "BarraEscala",
         "FlechaNorte", "PerfilTerreno", "Leyenda", "FormaItem",
         "EtiquetaItem", "NivelItem", "LlamadaItem", "CotaAngularItem",
         "CotaItem", "CotaRadialItem")


def default_of(f: dataclasses.Field) -> str:
    if f.default is not dataclasses.MISSING:
        value = f.default
    elif f.default_factory is not dataclasses.MISSING:
        value = f.default_factory()
    else:
        raise SystemExit(f"{f.name}: a required field")
    assert value is None or isinstance(value, (str, int, float, bool, list,
                                               dict)), (f.name, value)
    text = json.dumps(value)
    assert '"##' not in text
    return text


def main() -> None:
    out = ["// SPDX-License-Identifier: GPL-3.0-or-later",
           "// Copyright (C) 2026 Marco Sumari Tellez and IngeTrazo contributors.",
           "// Generated by scripts/golden/make_composition_schema.py from",
           "// core/composition.py; do not edit by hand.",
           "//! The fields of every sheet item, in declaration order, with their",
           "//! defaults as JSON text.",
           "",
           "pub type Schema = &'static [(&'static str, &'static str)];",
           ""]
    for name in KINDS:
        kind = getattr(comp, name)
        out.append(f"pub const {name.upper()}: Schema = &[")
        for f in dataclasses.fields(kind):
            out.append(f'    ("{f.name}", r##"{default_of(f)}"##),')
        out.append("];")
        out.append("")
    OUT.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"{len(KINDS)} item kinds -> {OUT}")


if __name__ == "__main__":
    main()
